// Writes ../EFFORT.md and ../PILOT-OFFER.md from src/data/effort.js and src/data/pilot-offer.js, so the site,
// the calculator and the guides use the same figures.
// Usage: npm run offer-docs            (write)
//        npm run offer-docs -- --check (exit 1 if either file is out of date)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { EFFORT, EFFORT_TOTALS, rangeText } from "../src/data/effort.js";
import { PILOT_OFFER as P } from "../src/data/pilot-offer.js";

const NOTE = "<!-- Generated by `npm run offer-docs` in docs-site from src/data/effort.js and src/data/pilot-offer.js. Edit those, not this file. -->";
const h = (r) => (r[0] === 0 && r[1] === 0 ? "-" : rangeText(r, "h"));

export function renderEffort() {
  const t = EFFORT_TOTALS;
  return [
    "# Effort breakdown: scoped member-pack pilot", "", NOTE, "",
    "**These are estimates** from building the synthetic Northwind example. No customer engagement has been timed yet;",
    "replace them with measured hours after the first pilot. \"You\" is the community owner or their team; \"we\" is",
    "whoever delivers the implementation.", "",
    "| Activity | What it involves | You, one-off | We, one-off | You, per month after handover |",
    "|---|---|---|---|---|",
    ...EFFORT.map(([, name, what, c1, w1, cm]) => `| ${name} | ${what} | ${h(c1)} | ${h(w1)} | ${h(cm)} |`),
    `| **Total** | | **${rangeText(t.customerOneOff)}** | **${rangeText(t.ourOneOff)}** | **${rangeText(t.customerMonthly)}** |`,
    "",
    `Of your one-off hours, ${rangeText(t.customerSetup)} are setup (before launch) and ${rangeText(t.customerPilot)} are`,
    "pilot logging spread over the pilot. The value calculator uses the midpoints of these ranges as its defaults.",
    "",
  ].join("\n");
}

const list = (items) => items.map((x) => `- ${x}`);

export function renderOffer() {
  const t = EFFORT_TOTALS;
  return [
    `# ${P.name}`, "", NOTE, "",
    P.summary, "",
    "The software is free and open source (MIT): you can do all of this yourself with the guides. This is the paid",
    "option for owners who want it built, tested and measured with them. No results are guaranteed.", "",
    "## Design-partner terms", "", "| | |", "|---|---|", ...P.terms.rows.map(([a, b]) => `| ${a} | ${b} |`), "",
    "## Scope", "", "| | |", "|---|---|", ...P.scope.map(([a, b]) => `| ${a} | ${b} |`), "",
    "## 1. What we commit to produce", "", "| Deliverable | What it is | Accepted when |", "|---|---|---|",
    ...P.deliverables.map(([a, b, c]) => `| ${a} | ${b} | ${c} |`), "", `**${P.paymentBasis}**`, "",
    "## 2. What you'll be able to observe", "", ...list(P.observe), "",
    "## 3. What the pilot tests, and nobody can promise", "", ...list(P.testing), "",
    "## Included revisions", "", ...list(P.revisions), "",
    "## What you provide", "", ...list(P.customerInputs), "",
    `Estimated time on your side: ${rangeText(t.customerSetup)} before launch and ${rangeText(t.customerPilot)} of`,
    `logging during the pilot. Ours: ${rangeText(t.ourOneOff)}. See [EFFORT.md](EFFORT.md); these are estimates until`,
    "measured.", "",
    "## What stays your responsibility", "", ...list(P.customerResponsibilities), "",
    "## Assumptions and dependencies", "", ...list(P.dependencies), "",
    "## Not included", "", ...list(P.exclusions), "",
    "## If acceptance checks fail", "", ...list(P.acceptanceFails), "",
    "## Optional maintenance after handover", "", ...list(P.maintenance), "",
    "## How it runs", "", ...P.process.map(([a, b], i) => `${i + 1}. **${a}**: ${b}`), "",
    "## How to enquire", "",
    ...(P.enquiry.privateDestination ? [`Privately: ${P.enquiry.privateDestination} (${P.enquiry.privateLabel}).`, ""] : []),
    `${P.enquiry.privateDestination ? "Or publicly" : "Publicly"}, with ${P.enquiry.label}: ${P.enquiry.destination}`, "",
    P.enquiry.requirements, "", "The form asks for:", "", ...list(P.enquiry.fields), "",
    "Kept for a private follow-up, never in the issue:", "", ...list(P.enquiry.privateLater), "",
    P.enquiry.privateNote, "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = { "EFFORT.md": renderEffort(), "PILOT-OFFER.md": renderOffer() };
  let stale = 0;
  for (const [name, text] of Object.entries(files)) {
    const target = fileURLToPath(new URL(`../../${name}`, import.meta.url));
    if (process.argv.includes("--check")) {
      const ok = existsSync(target) && readFileSync(target, "utf8") === text;
      if (!ok) stale += 1;
      console.log(ok ? `${name} is up to date` : `${name} is out of date: run npm run offer-docs`);
    } else {
      writeFileSync(target, text);
      console.log(`Wrote ${target}`);
    }
  }
  process.exit(stale ? 1 : 0);
}
